// Pure logic for scripts/spec-index.mjs and scripts/story-pack.mjs
// (roadmap 1.23.29, delivery.md 13): the section index of the specs and the
// reference resolution of a story pack.

export const INDEX_PATH = 'specs/INDEX.md';
export const PACK_WARN_BYTES = 60 * 1024;
export const PLAN_LINE_CAP = 400;

const HEADING = /^(#{2,4})\s+(.*\S)\s*$/;
const RULE = /^- (R\d+)\./;

/**
 * Headings (levels 2-4) and rule ids (`- R<n>.`) of one Markdown file, outside
 * code fences, each with its 1-based inclusive line range. A heading runs to
 * the line before the next heading of the same or a higher level; a rule to
 * the line before the next rule or heading. Trailing blank lines are trimmed.
 * Returns [{ start, end, label }] in file order.
 */
export function indexEntries(text) {
  const lines = text.split(/\r?\n/);
  const marks = []; // { line, level (0 = rule), label }
  let fence = null;
  lines.forEach((line, i) => {
    const f = /^\s*(```|~~~)/.exec(line);
    if (f) {
      if (!fence) fence = f[1];
      else if (f[1] === fence) fence = null;
      return;
    }
    if (fence) return;
    const h = HEADING.exec(line);
    if (h) return marks.push({ line: i + 1, level: h[1].length, label: line.trim() });
    const r = RULE.exec(line);
    if (r) marks.push({ line: i + 1, level: 0, label: `${r[1]} ${line.slice(r[0].length).trim().slice(0, 70)}`.trim() });
  });
  const last = lines.length;
  return marks.map((m, idx) => {
    let end = last;
    for (let j = idx + 1; j < marks.length; j++) {
      const n = marks[j];
      const closes = m.level === 0 || (n.level > 0 && n.level <= m.level);
      if (closes) {
        end = marks[j].line - 1;
        break;
      }
    }
    while (end > m.line && lines[end - 1].trim() === '') end--;
    return { start: m.line, end, label: m.label };
  });
}

/** `path:start-end  heading` lines of one file. */
export function indexLines(filePath, text) {
  return indexEntries(text).map((e) => `${filePath}:${e.start}-${e.end}  ${e.label}`);
}

/** The whole INDEX.md for `files` = [{ path, text }] (sorted by path). */
export function renderIndex(files) {
  const sorted = [...files].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const out = [
    '# Spec section index',
    '',
    'Generated by `node scripts/spec-index.mjs`; never edit by hand. `check-specs.py` fails when it is stale.',
    'Each line is `path:first-last  heading`, or a rule id. Read a range with `sed -n <first>,<last>p <path>`.',
    '',
  ];
  for (const f of sorted) {
    const lines = indexLines(f.path, f.text);
    if (lines.length) out.push(...lines, '');
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

/** Whether the committed index equals a freshly rendered one (line endings ignored). */
export function indexIsStale(committed, fresh) {
  return committed.replace(/\r\n/g, '\n') !== fresh.replace(/\r\n/g, '\n');
}

/** The lines `[start, end]` (1-based, inclusive) of `text`. */
export function sliceLines(text, start, end) {
  return text.split(/\r?\n/).slice(start - 1, end).join('\n');
}

/**
 * Plan references in a story entry: markdown links to `docs/plans/<file>.md`
 * (optionally with `#anchor`), and "plan section N" / "plan 1.24.x" mentions
 * (resolved against the plan file(s) the entry links). Returns
 * { files: [path], sections: [id] } with unique values in order.
 */
export function planReferences(entry) {
  const files = [];
  for (const m of entry.matchAll(/\]\((?:\.\.\/)*(?:\.\/)?(docs\/plans\/[\w.-]+\.md)(?:#[^)]*)?\)/g)) {
    if (!files.includes(m[1])) files.push(m[1]);
  }
  for (const m of entry.matchAll(/`?(docs\/plans\/[\w.-]+\.md)`?/g)) {
    if (!files.includes(m[1])) files.push(m[1]);
  }
  const sections = [];
  for (const m of entry.matchAll(/\bplan(?:\s+section)?s?\s+(\d+(?:\.\d+)*)/gi)) {
    if (!sections.includes(m[1])) sections.push(m[1]);
  }
  return { files, sections };
}

/**
 * Plan sections of `planText` whose heading starts with (or has a number
 * equal to) one of `sections`, as { start, end, text }. A heading's number is
 * its first dotted number or bare integer after the hashes (`## 1.24.6 — x`,
 * `## 3. Foo`, `## Section 3`).
 */
export function planSections(planText, sections) {
  const entries = indexEntries(planText).filter((e) => e.label.startsWith('#'));
  const lines = planText.split(/\r?\n/);
  const found = [];
  for (const id of sections) {
    for (const e of entries) {
      const num = /^#+\s+(?:Section\s+)?(\d+(?:\.\d+)*)/i.exec(e.label);
      if (num && num[1] === id && !found.some((f) => f.start === e.start)) {
        found.push({ id, start: e.start, end: e.end, text: lines.slice(e.start - 1, e.end).join('\n') });
      }
    }
  }
  return found;
}

/** Cap `text` at `maxLines` lines, noting the cut. */
export function capLines(text, maxLines = PLAN_LINE_CAP) {
  const lines = text.split('\n');
  if (lines.length <= maxLines) return text;
  return [...lines.slice(0, maxLines), `… (cut at ${maxLines} lines, ${lines.length - maxLines} more in the source)`].join('\n');
}

/**
 * Spec files named in an entry: `specs/...md` paths, with an optional
 * `#anchor` or "section <heading>" nearby. Returns [{ path, anchor }].
 */
export function specReferences(entry) {
  const out = [];
  for (const m of entry.matchAll(/(specs\/[\w./-]+?\.md)(?:#([\w-]+))?/g)) {
    if (!out.some((o) => o.path === m[1] && o.anchor === (m[2] ?? null))) out.push({ path: m[1], anchor: m[2] ?? null });
  }
  return out;
}

/** GitHub-style slug of a heading line, for `#anchor` matching. */
export function slug(heading) {
  return heading
    .replace(/^#+\s+/, '')
    .toLowerCase()
    .replace(/[`*_]/g, '')
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .trim()
    .replace(/\s/g, '-');
}

/**
 * The index lines of `specPath` that the pack should list: the sections whose
 * slug is `anchor`, or all headings (levels 2-3) when there is no anchor.
 */
export function specSections(specPath, text, anchor) {
  const entries = indexEntries(text).filter((e) => e.label.startsWith('#'));
  const chosen = anchor
    ? entries.filter((e) => slug(e.label) === anchor)
    : entries.filter((e) => e.label.startsWith('## ') || e.label.startsWith('### '));
  return chosen.map((e) => `${specPath}:${e.start}-${e.end}  ${e.label}`);
}

/** Code paths (`backend/src/...`, `frontend/src/...`, `scripts/...`) named in text. */
export function codePaths(text) {
  const out = [];
  for (const m of text.matchAll(/\b((?:backend|frontend)\/(?:src|e2e)\/[\w./@-]+\.(?:ts|html|scss|mjs)|scripts\/[\w./-]+\.(?:mjs|py))\b/g)) {
    if (!out.includes(m[1])) out.push(m[1]);
  }
  return out;
}

/** Top-level symbols with line numbers (`export`, class, function, @Component, selector). */
export function fileSymbols(text) {
  const out = [];
  text.split(/\r?\n/).forEach((line, i) => {
    if (/^(export\b|class\b|function\b|async function\b|@Component|\s+selector:)/.test(line)) {
      out.push(`${i + 1}: ${line.trim().slice(0, 110)}`);
    }
  });
  return out;
}

/** lessons.md bullets whose text matches one of the area keywords the pack needs. */
export const LESSON_KEYWORDS = {
  frontend: /\b(frontend|karma|ng test|angular|ChromeHeadless|axe)\b/i,
  backend: /\b(backend|jest|nest|eslint)\b/i,
  e2e: /\b(playwright|e2e|test:e2e)\b/i,
  specs: /\b(specs?|check-specs|gherkin)\b/i,
  agents: /\b(agents?|evals?|subagents?)\b/i,
};

export function applicableLessons(lessons, areas) {
  const res = areas.map((a) => LESSON_KEYWORDS[a]).filter(Boolean);
  return lessons
    .split(/\r?\n/)
    .filter((l) => l.startsWith('- ') && res.some((re) => re.test(l)));
}

/** Which lesson areas a set of paths and entry text touch. */
export function lessonAreas(entry, paths) {
  const areas = new Set(['specs']);
  if (paths.some((p) => p.startsWith('frontend/src'))) areas.add('frontend');
  if (paths.some((p) => p.startsWith('backend/'))) areas.add('backend');
  if (paths.some((p) => p.startsWith('frontend/e2e')) || /playwright|e2e/i.test(entry)) areas.add('e2e');
  if (/agent|eval/i.test(entry)) areas.add('agents');
  return [...areas];
}

