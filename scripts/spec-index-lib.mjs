/**
 * The story's entry as written: from its `#### <id> — ` heading to the next
 * heading of level 2-4 (or the end). Null when absent.
 */
export function storyEntry(roadmapText, id) {
  const lines = roadmapText.split(/\r?\n/);
  const start = lines.findIndex((l) => new RegExp(`^####\\s+${id.replace(/\./g, '\\.')}\\s+—`).test(l));
  if (start < 0) return null;
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    if (/^#{1,4}\s/.test(lines[i])) {
      end = i;
      break;
    }
  }
  while (end > start + 1 && lines[end - 1].trim() === '') end--;
  return { start: start + 1, end, text: lines.slice(start, end).join('\n') };
}

/** Short name of a spec file: `data-readiness` for specs/capabilities/data-readiness/spec.md, `data-model` for specs/system/data-model.md. */
export function specName(specPath) {
  const m = /^specs\/capabilities\/([\w-]+)\/spec\.md$/.exec(specPath) ?? /^specs\/(?:system|product)\/([\w-]+)\.md$/.exec(specPath);
  return m ? m[1] : null;
}

/**
 * Specs named by short name on "Specs:"-style lines (`data-readiness R2, R5`,
 * `data-model 3.15`), as [{ path, rules: ['R2', 'R5'] }]. `specPaths` is the
 * list of spec files on disk.
 */
export function namedSpecs(text, specPaths) {
  const lines = text.split(/\r?\n/).filter((l) => /\bspecs?\b/i.test(l));
  const out = [];
  for (const p of specPaths) {
    const name = specName(p);
    if (!name) continue;
    for (const l of lines) {
      const m = new RegExp(`(?<![\\w/-])${name}(?![\\w-])(?!\\.spec\\.ts)([^;.]*)`).exec(l);
      if (!m) continue;
      const rules = [...m[1].matchAll(/\bR(\d+)(?:\s*[–-]\s*R?(\d+))?/g)].flatMap((r) => {
        const a = Number(r[1]);
        const b = r[2] ? Number(r[2]) : a;
        return Array.from({ length: Math.min(b - a + 1, 30) }, (_, i) => `R${a + i}`);
      });
      const hit = out.find((o) => o.path === p);
      if (hit) hit.rules.push(...rules);
      else out.push({ path: p, rules });
    }
  }
  return out;
}

/** Index lines for a named spec: its `## ` headings plus the rule ids asked for. */
export function namedSpecSections(specPath, text, rules) {
  const entries = indexEntries(text);
  const out = [];
  for (const e of entries) {
    const isRule = /^R\d+ /.test(e.label);
    if (isRule ? rules.includes(e.label.split(' ')[0]) : e.label.startsWith('## ')) out.push(`${specPath}:${e.start}-${e.end}  ${e.label}`);
  }
  return out;
}
