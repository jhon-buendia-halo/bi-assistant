#!/usr/bin/env node
// Regenerates design/wireframes/_kit/icons.js: the lucide icons the wireframes use,
// read from the same lucide-angular package the app renders.
// Usage: node .claude/skills/wireframes/scripts/build-icons.mjs
// Needs frontend/node_modules (npm ci in frontend/), or LUCIDE_DIR pointing at
// lucide-angular/esm2020/src/icons/icons in another checkout.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
const wf = path.join(repo, 'design/wireframes');
const lucide = process.env.LUCIDE_DIR || path.join(repo, 'frontend/node_modules/lucide-angular/esm2020/src/icons/icons');
if (!fs.existsSync(lucide)) {
  console.error(`lucide icons not found at ${lucide}. Run "npm ci" in frontend/ or set LUCIDE_DIR.`);
  process.exit(1);
}

const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(html|js)$/.test(e.name) && e.name !== 'icons.js') files.push(p);
  }
})(wf);

// Pages name icons as data-lucide="..."; the kit's scripts name them as quoted strings,
// so any quoted lowercase word there that is a lucide icon is kept.
const names = new Set();
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(m[1]);
  if (f.endsWith('.js')) {
    for (const m of s.matchAll(/'([a-z0-9]+(?:-[a-z0-9]+)*)'/g)) {
      if (fs.existsSync(path.join(lucide, `${m[1]}.mjs`))) names.add(m[1]);
    }
  }
}

// Old lucide names the app still imports (bar-chart-3, filter, wand-2) live in the alias table.
const aliasFile = path.join(lucide, '../aliases/aliases.mjs');
const aliases = fs.existsSync(aliasFile) ? fs.readFileSync(aliasFile, 'utf8') : '';
const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
function iconFile(name) {
  const direct = path.join(lucide, `${name}.mjs`);
  if (fs.existsSync(direct)) return direct;
  const m = new RegExp(`default as ${pascal(name)}\\b[^;]*?from '\\.\\./icons/([a-z0-9-]+)'`).exec(aliases);
  return m ? path.join(lucide, `${m[1]}.mjs`) : null;
}

const out = {};
const missing = [];
for (const name of [...names].sort()) {
  const file = iconFile(name);
  if (!file) { missing.push(name); continue; }
  const src = fs.readFileSync(file, 'utf8');
  const body = /=\s*(\[[\s\S]*?\]);/.exec(src)[1];
  const nodes = [...body.matchAll(/\[\s*'(\w+)',\s*\{([^}]*)\},?\s*\]/g)].map(([, tag, attrs]) => {
    const a = [...attrs.matchAll(/(\w+):\s*'([^']*)'/g)].filter(([, k]) => k !== 'key').map(([, k, v]) => `${k}="${v}"`).join(' ');
    return `<${tag} ${a}/>`;
  });
  out[name] = nodes.join('');
}

const header = '// Generated by .claude/skills/wireframes/scripts/build-icons.mjs from lucide-angular. Do not edit.\n';
fs.writeFileSync(path.join(wf, '_kit/icons.js'), `${header}window.WF_ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};\n`);
console.log(`icons.js: ${Object.keys(out).length} icons${missing.length ? `; not in lucide: ${missing.join(', ')}` : ''}`);
if (missing.length) process.exitCode = 1;
