// The real Agent pulls in ESM-only packages Jest cannot require. This
// stand-in resolves `instructions`, `skills` and `tools` the way @mastra/core 1.66's
// Agent does: a function is called with `{ requestContext, mastra }`, and the
// requestContext defaults to an empty one when the caller passes none.
jest.mock('@mastra/core/agent', () => {
  const { RequestContext: Context } = jest.requireActual<
    typeof import('@mastra/core/request-context')
  >('@mastra/core/request-context');
  type Resolver = (args: { requestContext: unknown }) => unknown;
  const resolve = (value: unknown, requestContext: unknown) =>
    typeof value === 'function'
      ? (value as Resolver)({ requestContext })
      : value;
  return {
    Agent: class {
      constructor(
        private readonly config: {
          instructions: unknown;
          tools: unknown;
          skills: unknown;
        },
      ) {}
      getInstructions({ requestContext = new Context() } = {}) {
        return resolve(this.config.instructions, requestContext);
      }
      resolveSkills({ requestContext = new Context() } = {}) {
        return Promise.resolve(resolve(this.config.skills, requestContext));
      }
      listTools({ requestContext = new Context() } = {}) {
        return Promise.resolve(resolve(this.config.tools, requestContext));
      }
    },
  };
});
jest.mock('@mastra/memory', () => ({ Memory: class {} }));
jest.mock('../session-workspaces', () => ({
  SESSION_WORKSPACE_CONTEXT_KEY: 'session-workspace-id',
}));

import { readFileSync } from 'fs';
import { join } from 'path';
import { RequestContext } from '@mastra/core/request-context';
import { AGENT_TOOLS_CONTEXT_KEY } from '../agent-tools';
import type { InlineSkill } from '@mastra/core/skills';
import { AGENT_SKILLS_CONTEXT_KEY, type AgentSkill } from '../agent-skills';
import { appSkillBody } from '../app-skills';
import { setSkillOverrides } from '../skill-overrides';
import { assistantAgent, assistantVariant } from './assistant.agent';

/**
 * The full prompt (BA-217, regenerated by BA-223 without the `## Skills`
 * section and `read_file`). Every tool selected, or none on the context,
 * must still produce it byte for byte.
 */
const GOLDEN = readFileSync(
  join(__dirname, '__fixtures__', 'assistant-prompt.full.txt'),
  'utf8',
);

function contextWith(tools?: string[]): RequestContext {
  const requestContext = new RequestContext();
  if (tools) requestContext.set(AGENT_TOOLS_CONTEXT_KEY, tools);
  return requestContext;
}

const FULL_TOOLS = [
  'list_entities',
  'describe_entity',
  'sample_rows',
  'run_readonly_sql',
  'create_visual',
  'update_visual',
  'ask_clarification',
];

/** The assistant's prompt for a call; it is always a plain string. */
async function prompt(tools?: string[]): Promise<string> {
  return (await assistantAgent.getInstructions({
    requestContext: contextWith(tools),
  })) as string;
}

async function toolNames(tools?: string[]): Promise<string[]> {
  return Object.keys(
    await assistantAgent.listTools({ requestContext: contextWith(tools) }),
  );
}

describe('assistant tool selection (ADR-0021, agents.md 2.1)', () => {
  it('gives the unchanged full prompt and tools with no selection', async () => {
    expect((await assistantAgent.getInstructions()) as string).toBe(GOLDEN);
    expect(await prompt()).toBe(GOLDEN);
    expect(Object.keys(await assistantAgent.listTools())).toEqual(FULL_TOOLS);
  });

  it('gives the unchanged full prompt and tools with all three selected', async () => {
    const all = ['visuals', 'ask_clarification', 'sample_rows'];
    expect(await prompt(all)).toBe(GOLDEN);
    expect(await toolNames(all)).toEqual(FULL_TOOLS);
  });

  it('offers only the always-given tools and the selected ones, in order', async () => {
    expect(await toolNames(['sample_rows'])).toEqual([
      'list_entities',
      'describe_entity',
      'sample_rows',
      'run_readonly_sql',
    ]);
    expect(await toolNames(['visuals'])).toEqual([
      'list_entities',
      'describe_entity',
      'run_readonly_sql',
      'create_visual',
      'update_visual',
    ]);
    expect(await toolNames([])).toEqual([
      'list_entities',
      'describe_entity',
      'run_readonly_sql',
    ]);
  });

  it('lists only the offered tools and the matching rules in the prompt', async () => {
    const text = await prompt(['sample_rows']);
    const tools = text.slice(
      text.indexOf('## Tools'),
      text.indexOf('## Working rules'),
    );

    expect(tools).toContain('\n- sample_rows(');
    expect(tools).not.toMatch(/ask_clarification|create_visual|update_visual/);
    expect(tools).not.toContain('read_file');
    expect(text).toContain(
      "## Working rules\nYou can't ask the user a question back in this session.",
    );
    expect(text).toContain(
      "- You can't create or change visuals in this session.",
    );
    expect(text).not.toContain('## Skills');
  });

  it('builds each selection once', () => {
    expect(assistantVariant(['sample_rows'])).toBe(
      assistantVariant(['sample_rows']),
    );
    expect(assistantVariant()).not.toBe(assistantVariant([]));
  });
});

describe("the assistant's skills per call (ADR-0024, agents.md 7.3)", () => {
  const fiscal: AgentSkill = {
    id: 's1',
    name: 'fiscal-calendar',
    description: 'Use when a question names a fiscal year.',
    body: 'Our fiscal year starts on 1 July. See references/quarters.md and [[tool:sample_rows]].',
    files: [
      {
        path: 'references/quarters.md',
        content: 'Q1 is July to September. Check [[skill:curated-knowledge]].',
      },
    ],
  };
  const aaa: AgentSkill = { ...fiscal, id: 's2', name: 'aaa-first', files: [] };

  async function skillsWith(skills?: AgentSkill[]): Promise<InlineSkill[]> {
    const requestContext = contextWith();
    if (skills) requestContext.set(AGENT_SKILLS_CONTEXT_KEY, skills);
    return (await (
      assistantAgent as unknown as {
        resolveSkills(a: { requestContext: RequestContext }): unknown;
      }
    ).resolveSkills({ requestContext })) as InlineSkill[];
  }

  afterEach(() => setSkillOverrides([]));

  it('is the built-in on-demand skill alone on a plain call', async () => {
    const plain = await skillsWith(undefined);
    expect(plain.map((skill) => skill.name)).toEqual(['curated-knowledge']);
    expect(plain[0].instructions).toBe(appSkillBody('curated-knowledge'));
    expect((await skillsWith([])).map((skill) => skill.name)).toEqual([
      'curated-knowledge',
    ]);
  });

  it("serves an in-app override's content in place of the shipped skill", async () => {
    setSkillOverrides([
      {
        name: 'curated-knowledge',
        description: 'Use when the edited description applies.',
        body: 'Edited body.',
        files: [],
        baseHash: 'h',
      },
    ]);
    const [skill] = await skillsWith(undefined);
    expect(skill.description).toBe('Use when the edited description applies.');
    expect(skill.instructions).toBe('Edited body.');
  });

  it("adds the agent's skills, sorted by name, with links resolved in the instructions and the references", async () => {
    const skills = await skillsWith([fiscal, aaa]);
    expect(skills.map((skill) => skill.name)).toEqual([
      'aaa-first',
      'curated-knowledge',
      'fiscal-calendar',
    ]);
    const added = skills.find((skill) => skill.name === 'fiscal-calendar')!;
    expect(added.description).toBe(fiscal.description);
    expect(added.instructions).toBe(
      'Our fiscal year starts on 1 July. See references/quarters.md and the "sample_rows" tool.',
    );
    expect(added.references).toEqual(['quarters.md']);
    expect(added.__referenceContents).toEqual({
      'quarters.md':
        'Q1 is July to September. Check the "curated-knowledge" skill.',
    });
    expect(JSON.stringify(skills)).not.toContain('[[');
  });

  it('lets an agent skill replace a same-named folder skill', async () => {
    const replacing: AgentSkill = {
      ...fiscal,
      name: 'curated-knowledge',
      body: 'The agent’s own.',
      files: [],
    };
    const skills = await skillsWith([replacing]);
    expect(skills.map((skill) => skill.name)).toEqual(['curated-knowledge']);
    expect(skills[0].instructions).toBe('The agent’s own.');
  });

  it('keeps skills out of the prompt and the tools out of read_file', async () => {
    const requestContext = contextWith();
    requestContext.set(AGENT_SKILLS_CONTEXT_KEY, [fiscal]);
    const text = (await assistantAgent.getInstructions({
      requestContext,
    })) as string;
    expect(text).toBe(GOLDEN);
    expect(text).not.toMatch(/## Skills|<available_skills>|\[\[|read_file/);
    const tools = Object.keys(
      await assistantAgent.listTools({ requestContext }),
    );
    expect(tools).not.toContain('read_file');
    expect(tools).not.toContain('run_skill_script');
  });
});
