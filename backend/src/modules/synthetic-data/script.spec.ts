import { createHash } from 'node:crypto';
import type {
  DialectWriter,
  SyntheticValue,
  WriterTable,
} from './dialects/writer';
import type { ExportDescription, GeneratedTable } from './generator/contract';
import { generateTables } from './generator/generate';
import { validateScriptRequest } from './generator/plan';
import {
  column,
  rel,
  worldCupProfile,
} from './generator/world-cup-profile.stub';
import { createScript, describeExport } from './script';
import type { SampledProfile } from './types';

const WC = 'world_cup.public.';

/** A tiny fake writer: the real ones are built by other units. */
function fakeWriter(over: Partial<DialectWriter> = {}): DialectWriter {
  const q = (s: string): string => `"${s}"`;
  const lit = (v: SyntheticValue): string => {
    if (v === null) return 'NULL';
    if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
    if (typeof v === 'string') return `'${v.replace(/'/g, "''")}'`;
    if (v.kind === 'neutral') return "''";
    return v.kind === 'number' ? v.text : `'${v.text}'`;
  };
  return {
    dialect: 'postgres',
    quoteIdent: q,
    qualify: (s, t) => `${q(s)}.${q(t)}`,
    ddlType: (c) =>
      c.type === 'jsonb'
        ? { ddl: 'text', note: 'jsonb written as text' }
        : { ddl: c.type },
    literal: (v) => lit(v),
    begin: () => ['BEGIN;'],
    end: () => ['COMMIT;'],
    createSchema: (s) => `CREATE SCHEMA IF NOT EXISTS ${q(s)};`,
    createTable: (s, t: WriterTable, keys) =>
      `CREATE TABLE ${q(s)}.${q(t.targetName)} (\n${t.columns
        .map(
          (c) => `  ${q(c.name)} ${c.ddlType}${c.notNull ? ' NOT NULL' : ''}`,
        )
        .join(
          ',\n',
        )}${keys && t.primaryKey.length ? `,\n  PRIMARY KEY (${t.primaryKey.map(q).join(', ')})` : ''}\n);`,
    insert: (s, t, rows) =>
      `INSERT INTO ${q(s)}.${q(t.targetName)} (${t.columns.map((c) => q(c.name)).join(', ')}) VALUES\n${rows
        .map((r) => `(${r.map(lit).join(', ')})`)
        .join(',\n')};`,
    addForeignKey: (s, r, from, to) =>
      `ALTER TABLE ${q(s)}.${q(from.targetName)} ADD FOREIGN KEY (${r.fromColumns.join(', ')}) REFERENCES ${q(s)}.${q(to.targetName)};`,
    headerNotes: () => ['standard_conforming_strings is assumed on'],
    ...over,
  };
}

function description(
  p: SampledProfile,
  request: Record<string, unknown>,
  at = '2026-11-11T12:00:00.000Z',
): ExportDescription {
  return {
    content: 'synthetic',
    datasetName: p.datasetName,
    datasourceKind: p.dialect,
    appVersion: '0.47.0',
    generatedAt: new Date(at),
    profile: p,
    plan: validateScriptRequest(p, request),
    notes: [],
  };
}

function script(
  request: Record<string, unknown> = {},
  at?: string,
  p = worldCupProfile(),
  writer = fakeWriter(),
) {
  const d = description(p, request, at);
  let calls = 0;
  const s = createScript({
    description: d,
    writer,
    tables: () => {
      calls++;
      return generateTables(p, d.plan);
    },
  });
  const text = [...s.chunks()].join('');
  return { s, text, calls };
}

describe('createScript', () => {
  const { s, text, calls } = script({ defaultRowCount: 30 });
  const lines = text.split('\n');

  it('is LF only and ends with a single "\\n"', () => {
    expect(text.includes('\r')).toBe(false);
    expect(text.endsWith(';\n')).toBe(true);
    expect(text.endsWith('\n\n')).toBe(false);
  });

  it('starts with the time line and the sha line, then the header, as SQL comments', () => {
    expect(lines[0]).toBe(
      '-- Synthetic data for dataset "World Cup" (PostgreSQL), generated by Questions to Insights 0.47.0 on 2026-11-11T12:00:00.000Z',
    );
    expect(lines[1]).toBe(
      `-- sha256 (without this header line and the time line): ${s.sha256}`,
    );
    expect(lines[2]).toMatch(
      /^-- Profile 00000000-0000-4000-8000-000000000001, sampled at /,
    );
    expect(text).toContain(
      '-- Seed 1: the same profile, settings and seed give the same data\n',
    );
    expect(text).toContain(
      `--   ${WC}goals -> goals: 30 rows (sampled 100 of about 100 rows, method full)\n`,
    );
    expect(text).toContain(
      '-- Column types replaced:\n--   world_cup.public.goals.payload: jsonb written as text\n',
    );
    expect(text).toContain(
      '-- PostgreSQL notes:\n--   standard_conforming_strings is assumed on\n',
    );
    expect(text).toContain(
      `--   ${WC}tournaments.tournament_year: the observed range holds fewer distinct values than 30 rows: generated as a sequence from the observed minimum\n`,
    );
  });

  it('the sha256 is the hash of every byte after the first two lines', () => {
    const rest = text.slice(text.indexOf('\n', text.indexOf('\n') + 1) + 1);
    expect(createHash('sha256').update(rest, 'utf8').digest('hex')).toBe(
      s.sha256,
    );
  });

  it('orders BEGIN, schema, every CREATE TABLE, the INSERTs, the FK ALTERs, COMMIT', () => {
    const at = (needle: string): number => text.indexOf(needle);
    const lastCreate = text.lastIndexOf('CREATE TABLE');
    expect(at('BEGIN;')).toBeLessThan(
      at('CREATE SCHEMA IF NOT EXISTS "synthetic";'),
    );
    expect(at('CREATE SCHEMA')).toBeLessThan(at('CREATE TABLE'));
    expect(lastCreate).toBeLessThan(at('INSERT INTO'));
    expect(text.lastIndexOf('INSERT INTO')).toBeLessThan(at('ALTER TABLE'));
    expect(text.lastIndexOf('ALTER TABLE')).toBeLessThan(at('COMMIT;'));
    expect((text.match(/^ALTER TABLE/gm) ?? []).length).toBe(15);
    expect(text.endsWith('COMMIT;\n')).toBe(true);
    // Parents before children.
    expect(at('INSERT INTO "synthetic"."teams"')).toBeLessThan(
      at('INSERT INTO "synthetic"."matches"'),
    );
  });

  it('counts the rows, and calls tables() twice (hash, then stream)', () => {
    expect(s.rows).toBe(9 * 30);
    expect(calls).toBe(2);
  });

  it('batches INSERTs at 500 rows', () => {
    const big = script({
      defaultRowCount: 1,
      rowCounts: { [`${WC}goals`]: 1201 },
    }).text;
    const goalInserts = big
      .split('\n\n')
      .filter((b) => b.startsWith('INSERT INTO "synthetic"."goals"'));
    expect(goalInserts.map((b) => b.split('\n').length - 1)).toEqual([
      500, 500, 201,
    ]);
  });

  it('leaves the FK ALTERs out without constraints', () => {
    expect(script({ includeConstraints: false }).text).not.toContain(
      'ALTER TABLE',
    );
  });

  it('normalises CRLF from a writer to LF', () => {
    const crlf = fakeWriter({
      createSchema: (sch) => `CREATE SCHEMA ${sch};\r\n`,
    });
    expect(
      script({}, undefined, worldCupProfile(), crlf).text.includes('\r'),
    ).toBe(false);
  });
});

describe('determinism of the script', () => {
  it('same input: same sha256 at another time; another seed: another sha256', () => {
    const a = script({ seed: 5 }, '2026-11-11T12:00:00.000Z');
    const b = script({ seed: 5 }, '2027-01-01T00:00:00.000Z');
    expect(a.s.sha256).toBe(b.s.sha256);
    expect(a.text.split('\n').slice(2)).toEqual(b.text.split('\n').slice(2));
    expect(script({ seed: 6 }).s.sha256).not.toBe(a.s.sha256);
  });
});

describe('describeExport', () => {
  it('never holds a sampled value: no categorical topValue, no range extreme', () => {
    const p = worldCupProfile();
    p.tables[4].columns[3] = column('group_letter', 'text', {
      kind: 'categorical',
      strategy: 'categorical',
      topValues: [{ value: 'SECRET_TOP_VALUE', fraction: 1 }],
      otherFraction: 0,
    });
    const lines = describeExport(description(p, { defaultRowCount: 50 })).join(
      '\n',
    );
    expect(lines).not.toContain('SECRET_TOP_VALUE');
    expect(lines).not.toContain('2018');
    expect(lines).not.toContain('2022-');
  });

  it('lists clamped, renamed, dropped and not-synthesized items', () => {
    const p = worldCupProfile();
    p.relationships.push(rel('goals', ['assist_player_id'], 'elsewhere'));
    p.tables[0] = {
      ...p.tables[0],
      key: 'other.public.goals',
      namespace: 'other',
      name: 'goals',
    };
    const d = description(p, {
      rowCounts: {
        [`${WC}tournament_teams`]: 2,
        [`${WC}players`]: 2,
        [`${WC}squad_members`]: 9,
      },
    });
    const lines = describeExport(d);
    expect(lines).toContain(
      'Clamped tables (a key made of foreign keys allows no more distinct rows):',
    );
    expect(lines).toContain(`  ${WC}squad_members: 4 rows instead of 9`);
    expect(lines).toContain('Renamed tables (the same name in two schemas):');
    expect(lines).toContain('  other.public.goals -> other_goals');
    expect(lines).toContain(`  ${WC}goals -> public_goals`);
    expect(lines).toContain(
      'Relationships not kept (the parent table is not in the profile):',
    );
    expect(lines).toContain(
      `  ${WC}goals (assist_player_id) -> world_cup.public.elsewhere (id)`,
    );
    expect(lines).toContain('Columns not synthesized:');
    expect(lines).toContain(
      `  ${WC}goals.payload: Type not synthesized: generated as NULL`,
    );
  });

  it('says REAL DATA first for a sample export, with no seed line', () => {
    const p = worldCupProfile();
    const d: ExportDescription = {
      ...description(p, {}),
      content: 'sample',
      notes: ['public.goals could not be read'],
    };
    const lines = describeExport(d);
    expect(lines[0]).toBe(
      'Sample rows (REAL DATA) for dataset "World Cup" (PostgreSQL), read by Questions to Insights 0.47.0 on 2026-11-11T12:00:00.000Z',
    );
    expect(lines.some((l) => l.startsWith('Seed '))).toBe(false);
    expect(lines.slice(-2)).toEqual([
      'Notes:',
      '  public.goals could not be read',
    ]);
  });

  it('keeps every line on one line', () => {
    const p = { ...worldCupProfile(), datasetName: 'Two\r\nLines' };
    for (const l of describeExport(description(p, {})))
      expect(l).not.toMatch(/[\r\n]/);
  });

  it('accepts any iterable of tables (an array works as well as the generator)', () => {
    const p = worldCupProfile();
    const d = description(p, { defaultRowCount: 3 });
    const arr: GeneratedTable[] = [...generateTables(p, d.plan)].map((t) => ({
      ...t,
      rows: t.rows,
    }));
    const s = createScript({
      description: d,
      writer: fakeWriter(),
      tables: () => arr,
    });
    expect(s.rows).toBe(27);
    expect(s.sha256).toBe(script({ defaultRowCount: 3 }).s.sha256);
  });
});
