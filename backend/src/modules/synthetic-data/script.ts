// The export header and the SQL script (plan 2.4, 2.5, 3.2, 10). Pure apart from hashing.
//
// Script layout, LF only, ending with "\n":
//   -- <first header line: dataset, app version, generated on <ISO>>   (not hashed)
//   -- sha256 (without this header line and the time line): <hex>     (not hashed)
//   -- <the other header lines>
//   <blank>
//   writer.begin(), CREATE SCHEMA, every CREATE TABLE (emission order),
//   INSERTs in batches of INSERT_BATCH_ROWS, FK ALTERs after every insert, writer.end().
// The SHA-256 covers every byte after the second line, so it is stable across runs.

import { createHash } from 'node:crypto';
import type {
  DialectWriter,
  SyntheticValue,
  WriterColumn,
  WriterTable,
} from './dialects/writer';
import type { ExportDescription, GeneratedTable } from './generator/contract';
import { uniqueRangeFallsBack } from './generator/values/unique';
import { INSERT_BATCH_ROWS } from './limits';
import type { SampledRelationship, SyntheticDialect } from './types';

export const SHA_LINE_PREFIX =
  'sha256 (without this header line and the time line): ';

const KIND_LABEL: Record<SyntheticDialect, string> = {
  postgres: 'PostgreSQL',
  databricks: 'Databricks',
};

/** Header text never spans lines. */
const oneLine = (s: string): string => s.replace(/[\r\n]+/g, ' ');

const relText = (r: SampledRelationship): string =>
  `${r.fromTable} (${r.fromColumns.join(', ')}) -> ${r.toTable} (${r.toColumns.join(', ')})`;

/**
 * The header lines of a script, or the README of a CSV zip or workbook, without a
 * comment prefix. Holds names, counts and settings only: never a sampled value.
 */
export function describeExport(d: ExportDescription): string[] {
  const kind = KIND_LABEL[d.datasourceKind] ?? d.datasourceKind;
  const when = d.generatedAt.toISOString();
  const synthetic = d.content === 'synthetic';
  const lines: string[] = [
    synthetic
      ? `Synthetic data for dataset "${d.datasetName}" (${kind}), generated by Questions to Insights ${d.appVersion} on ${when}`
      : `Sample rows (REAL DATA) for dataset "${d.datasetName}" (${kind}), read by Questions to Insights ${d.appVersion} on ${when}`,
  ];
  const p = d.profile;
  lines.push(
    `Profile ${p.profileId}, sampled at ${p.generatedAt}, up to ${p.sampleSize} rows per table`,
  );
  if (synthetic) {
    lines.push(
      `Seed ${d.plan.seed}: the same profile, settings and seed give the same data`,
    );
  } else {
    lines.push(
      'These are real rows read from the datasource: handle them as the source data',
    );
  }
  lines.push(`Target schema: ${d.plan.targetSchema}`);
  lines.push(
    `Keys and constraints: ${d.plan.includeConstraints ? 'included' : 'not included'}`,
  );

  const byKey = new Map(p.tables.map((t) => [t.key, t]));
  lines.push(`Tables (${d.plan.tables.length}):`);
  for (const t of d.plan.tables) {
    const src = byKey.get(t.key);
    const sampled = src
      ? `sampled ${src.sampledRows}${
          src.rowCountEstimate !== null
            ? ` of about ${src.rowCountEstimate}`
            : ''
        } rows, method ${src.method}`
      : 'not sampled';
    lines.push(
      synthetic
        ? `  ${t.key} -> ${t.targetName}: ${t.rows} rows (${sampled})`
        : `  ${t.key} -> ${t.targetName}: ${t.rows} rows`,
    );
  }

  const clamped = d.plan.tables.filter((t) => t.clampedFrom !== undefined);
  if (clamped.length > 0) {
    lines.push(
      'Clamped tables (a key made of foreign keys allows no more distinct rows):',
    );
    for (const t of clamped)
      lines.push(`  ${t.key}: ${t.rows} rows instead of ${t.clampedFrom}`);
  }

  const renamed = d.plan.tables.filter(
    (t) => byKey.get(t.key)?.name !== t.targetName,
  );
  if (renamed.length > 0) {
    lines.push('Renamed tables (the same name in two schemas):');
    for (const t of renamed) lines.push(`  ${t.key} -> ${t.targetName}`);
  }

  if (d.plan.droppedRelationships.length > 0) {
    lines.push(
      'Relationships not kept (the parent table is not in the profile):',
    );
    for (const r of d.plan.droppedRelationships) lines.push(`  ${relText(r)}`);
  }

  if (synthetic) {
    const notSynth: string[] = [];
    const ranges: string[] = [];
    for (const t of d.plan.tables) {
      const src = byKey.get(t.key);
      for (const c of src?.columns ?? []) {
        if (c.strategy === 'null-only' || c.strategy === 'constant') {
          notSynth.push(
            `  ${t.key}.${c.name}: ${
              c.note ??
              (c.strategy === 'null-only'
                ? 'generated as NULL'
                : 'generated as a neutral value')
            }`,
          );
        }
        if (c.strategy === 'unique-range' && uniqueRangeFallsBack(c, t.rows)) {
          ranges.push(
            `  ${t.key}.${c.name}: the observed range holds fewer distinct values than ${t.rows} rows: generated as a sequence from the observed minimum`,
          );
        }
      }
    }
    if (notSynth.length > 0)
      lines.push('Columns not synthesized:', ...notSynth);
    if (ranges.length > 0)
      lines.push('Distinct numbers beyond the observed range:', ...ranges);
  }

  if (d.notes.length > 0) {
    lines.push('Notes:');
    for (const n of d.notes) lines.push(`  ${n}`);
  }
  return lines.map(oneLine);
}

export interface ScriptInput {
  description: ExportDescription;
  writer: DialectWriter;
  /** Called twice: once for the hash, once to stream. */
  tables: () => Iterable<GeneratedTable>;
}

export interface Script {
  sha256: string;
  rows: number;
  chunks(): Iterable<string>;
}

/** A statement as one LF-only piece ending with exactly one "\n". */
const stmt = (s: string): string =>
  `${s.replace(/\r\n?/g, '\n').replace(/\n+$/, '')}\n`;

const comment = (line: string): string =>
  line === '' ? '--\n' : `-- ${line}\n`;

export function createScript(input: ScriptInput): Script {
  const { description: d, writer } = input;
  const { targetSchema, includeConstraints } = d.plan;

  // Pass 1: every table's columns (rows are generated lazily, so this is cheap).
  const all: (GeneratedTable | undefined)[] = [...input.tables()];
  const meta: WriterTable[] = [];
  const typeNotes: string[] = [];
  for (const t of all as GeneratedTable[]) {
    const columns: WriterColumn[] = t.columns.map((c) => {
      const { ddl, note } = writer.ddlType(c);
      if (note) typeNotes.push(`  ${t.key}.${c.name}: ${note}`);
      return { name: c.name, ddlType: ddl, notNull: !c.nullable, source: c };
    });
    meta.push({
      key: t.key,
      targetName: t.targetName,
      columns,
      primaryKey: t.primaryKey,
      uniqueKeys: t.uniqueKeys,
    });
  }

  const described = describeExport(d);
  const header = [...described];
  if (typeNotes.length > 0)
    header.push('Column types replaced:', ...typeNotes.map(oneLine));
  const seen = new Set(described.map((l) => l.trim()));
  const writerNotes = writer
    .headerNotes()
    .filter((n) => !seen.has(oneLine(n).trim()));
  if (writerNotes.length > 0) {
    header.push(`${KIND_LABEL[writer.dialect] ?? writer.dialect} notes:`);
    header.push(...writerNotes.map((n) => `  ${oneLine(n)}`));
  }
  const [firstLine, ...restHeader] = header;

  const metaByKey = new Map(meta.map((m) => [m.key, m]));

  function* body(
    tables: Iterable<GeneratedTable>,
    onRows?: (n: number) => void,
  ): Generator<string> {
    for (const l of restHeader) yield comment(l);
    yield '\n';
    for (const l of writer.begin()) yield stmt(l);
    yield stmt(writer.createSchema(targetSchema));
    for (const m of meta) {
      yield '\n';
      yield stmt(writer.createTable(targetSchema, m, includeConstraints));
    }
    for (const t of tables) {
      const m = metaByKey.get(t.key);
      if (!m) continue;
      const rows: SyntheticValue[][] = t.rows;
      onRows?.(rows.length);
      for (let i = 0; i < rows.length; i += INSERT_BATCH_ROWS) {
        yield '\n';
        yield stmt(
          writer.insert(targetSchema, m, rows.slice(i, i + INSERT_BATCH_ROWS)),
        );
      }
    }
    if (includeConstraints) {
      let first = true;
      for (const r of d.plan.relationships) {
        const from = metaByKey.get(r.fromTable);
        const to = metaByKey.get(r.toTable);
        if (!from || !to) continue;
        if (first) yield '\n';
        first = false;
        yield stmt(writer.addForeignKey(targetSchema, r, from, to));
      }
    }
    const end = writer.end();
    if (end.length > 0) {
      yield '\n';
      for (const l of end) yield stmt(l);
    }
  }

  // Pass 1 continued: hash every byte after the time and sha lines. Each table is
  // dropped once written, so its generated rows can be freed.
  const hash = createHash('sha256');
  let rows = 0;
  function* fromCollected(): Generator<GeneratedTable> {
    for (let i = 0; i < all.length; i++) {
      const t = all[i]!;
      all[i] = undefined;
      yield t;
    }
  }
  for (const piece of body(fromCollected(), (n) => (rows += n)))
    hash.update(piece, 'utf8');
  const sha256 = hash.digest('hex');

  return {
    sha256,
    rows,
    *chunks(): Generator<string> {
      yield comment(firstLine);
      yield comment(`${SHA_LINE_PREFIX}${sha256}`);
      yield* body(input.tables());
    },
  };
}
